import java.util.*;

// Creating Class with name ConvertKmToMiles indicating the purpose is to display convertion of kilometer into miles

public class ConvertKmToMiles 
{
	public static void main (String args [])
	{
		// create double variable Distance (in kilometers)
		double Distance = 10.8;
		
		// create a result variable to calculate the conversion of kilometer into miles
		double result = 10.8 /1.6;
		
		//Display the result
		System.out.println("The distance " + Distance + "km in miles is " + result);
	}
}